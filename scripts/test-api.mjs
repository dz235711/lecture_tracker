import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:5173';
const unauthenticated = await fetch(`${base}/api/planner`);
assert.equal(unauthenticated.status, 401);
const signIn = await fetch(`${base}/signin-with-chatgpt?return_to=/`, { redirect: 'manual' });
const cookie = signIn.headers.get('set-cookie').split(';')[0];
const headers = { 'Content-Type': 'application/json', Origin: base, Cookie: cookie };
const get = () => fetch(`${base}/api/planner`, { headers: { Cookie: cookie } });
const initial = await (await get()).json();
assert.ok(initial.data.term); assert.equal(initial.data.lectures[0].start, '09:30');
assert.equal(initial.data.lectures[0].end, '11:00');
assert.equal(initial.data.term.start, '2026-09-28');
assert.equal(Object.keys(initial.data.completed).length, 1);
const denied = await fetch(`${base}/api/planner`, { method: 'PUT', headers: { ...headers, Origin: 'https://another.example' }, body: JSON.stringify(initial) });
assert.equal(denied.status, 403);
const invalid = await fetch(`${base}/api/planner`, { method: 'PUT', headers, body: JSON.stringify({ ...initial, data: { ...initial.data, term: { ...initial.data.term, end: '2026-02-30' } } }) });
assert.equal(invalid.status, 400);
const saved = await fetch(`${base}/api/planner`, { method: 'PUT', headers, body: JSON.stringify(initial) });
assert.equal(saved.status, 200);
const stale = await fetch(`${base}/api/planner`, { method: 'PUT', headers, body: JSON.stringify(initial) });
assert.equal(stale.status, 409);
const after = await (await get()).json();
assert.deepEqual(after.data, initial.data);
assert.equal(after.revision, initial.revision + 1);
console.log('Passed: saved term dates and times, completion persistence, sign-in required, origin checks, invalid input rejected, and stale saves prevented.');
